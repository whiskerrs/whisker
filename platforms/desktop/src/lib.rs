//! Shared native Desktop Host for Whisker.
//!
//! This crate is deliberately outside Whisker's runtime/engine dependency
//! graph. A thin OS adapter and CNG-generated `gen/<os>` executable use it as
//! the composition root: the Host owns the native window and event loop, while
//! [`whisker::RuntimeInstance`] owns application state, layout, and frame
//! production.
//!
//! The Host retains accepted semantic frames in a [`DesktopSurface`]-style
//! projection, shapes text with the platform font collection, and paints the
//! resulting display list through the target `wgpu` backend. Runtime state and
//! Taffy remain above this crate; GPU resources and prepared glyph buffers
//! remain below it.

