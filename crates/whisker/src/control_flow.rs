//! Built-in control-flow components — `for_each` (keyed list) and
//! `show` (conditional).
//!
//! Both are written exactly as a user-defined control flow would be:
//! regular `#[component]` functions that allocate a *fragment*
//! ([`create_phantom_element`](whisker_runtime::view::create_phantom_element)),
//! install a reactive [`effect`](whisker_runtime::reactive::effect) to
//! diff their input source, and return the fragment. There is no
//! `ControlFlow` trait and no special path through the surrounding
//! builder — `render!` treats `ForEach(...)` / `Show(...)` like any
//! other user component.
//!
//! A user implementing their own control flow follows the same
//! outline:
//!
//! ```ignore
//! use whisker::prelude::*;
//!
//! #[whisker::component]
//! pub fn animated_show(
//!     when: ReadSignal<bool>,
//!     duration_ms: u32,
//!     children: Children,
//! ) -> Element {
//!     let frag = whisker::runtime::view::create_phantom_element();
//!     let mounted: std::rc::Rc<std::cell::RefCell<Option<_>>> =
//!         std::rc::Rc::new(std::cell::RefCell::new(None));
//!     effect(move || {
//!         /* ... mount / unmount under `frag` based on `when.get()` ... */
//!     });
//!     frag
//! }
//! ```
//!
//! The fragment's phantom-hoisting machinery (see
//! [`docs/wrapper-less-control-flow-design.md`](https://github.com/whiskerrs/whisker/blob/main/docs/wrapper-less-control-flow-design.md))
//! routes the mounted children to the nearest non-phantom ancestor
//! in the Host tree, so the on-screen DOM is wrapper-less while
//! the user code keeps its hierarchical mental model.

use std::cell::{Cell, RefCell};
use std::collections::HashMap;
use std::hash::Hash;
use std::rc::Rc;

use whisker_runtime::reactive::{Owner, ReadSignal, RwSignal, effect};
use whisker_runtime::view::{
    Children, EachFn, Element, Fallback, ItemFn, KeyFn, WhenFn, append_child,
    create_phantom_element, insert_child_at, remove_child,
};

use crate::component;

// ---------------------------------------------------------------------------
// `for_each` → `ForEach` (PascalCase marker generated by `#[component]`)
// ---------------------------------------------------------------------------

/// Keyed-list control flow. Returns a fragment populated with one
/// element per item; reactive updates re-key against the previous
/// render so survivors keep their per-item owners (and any reactive
/// state inside) intact.
///
/// `each` is the reactive items source (a `Fn() -> Vec<T>` closure
/// wrapped in [`EachFn`] via `Into`). On every dep change the effect
/// recomputes it, derives new keys via `key`, and diffs against the
/// previous frame:
///
///   - kept (same key) → owner + element preserved, item signal set
///     to the new value
///   - new key → fresh owner, `children(item)` runs with a signal of
///     the item
///   - missing key → owner disposed, element detached
///
/// Repeated keys are told apart by occurrence, so each duplicate gets
/// its own row. Only rows whose position changed are moved, which keeps
/// a focused native input in an untouched row focused.
#[component]
pub fn for_each<T, K>(each: EachFn<T>, key: KeyFn<T, K>, children: ItemFn<ReadSignal<T>>) -> Element
where
    T: 'static,
    K: Eq + Hash + Clone + 'static,
{
    let frag = create_phantom_element();

    struct Entry<T: 'static> {
        owner: Owner,
        handle: Element,
        item: RwSignal<T>,
    }
    type Entries<K, T> = HashMap<(K, usize), Entry<T>>;
    let entries: Rc<RefCell<Entries<K, T>>> = Rc::new(RefCell::new(HashMap::new()));

    // The outer body is a `FnMut` (per `#[component]`'s hot-reload
    // wrapper), so the closure props must be cloned in rather than
    // moved out of it.
    let each = each.clone();
    let key = key.clone();
    let children = children.clone();

    effect(move || {
        let mut old = std::mem::take(&mut *entries.borrow_mut());
        let mut new_entries: Entries<K, T> = HashMap::new();
        let mut occurrences: HashMap<K, usize> = HashMap::new();
        let mut ordered: Vec<((K, usize), Option<T>)> = Vec::new();

        for item in each.call() {
            let k = key.call(&item);
            let n = occurrences.entry(k.clone()).or_insert(0);
            let slot = (k, *n);
            *n += 1;
            if let Some(existing) = old.remove(&slot) {
                existing.item.set(item);
                new_entries.insert(slot.clone(), existing);
                ordered.push((slot, None));
            } else {
                ordered.push((slot, Some(item)));
            }
        }

        for (_, entry) in old.drain() {
            remove_child(frag, entry.handle);
            entry.owner.dispose();
        }

        for (index, (slot, item)) in ordered.into_iter().enumerate() {
            match item {
                Some(item) => {
                    let owner = Owner::new(None);
                    let (handle, item) = owner.with(|| {
                        let item = RwSignal::new(item);
                        let h = children.call(item.read_only());
                        insert_child_at(frag, h, index);
                        (h, item)
                    });
                    new_entries.insert(
                        slot,
                        Entry {
                            owner,
                            handle,
                            item,
                        },
                    );
                }
                None => insert_child_at(frag, new_entries[&slot].handle, index),
            }
        }

        *entries.borrow_mut() = new_entries;
    });

    frag
}

// ---------------------------------------------------------------------------
// `show` → `Show` (PascalCase marker generated by `#[component]`)
// ---------------------------------------------------------------------------

/// Conditional control flow. When `when` reads true the `children`
/// closure's element is mounted under the returned fragment; when
/// false, `fallback` (if any) is mounted instead. On every flip the
/// mounted branch's owner is disposed before the other branch is
/// instantiated, so reactive state from the previous branch can't
/// leak.
///
/// The branch is rebuilt only when the condition **changes**, not on
/// every dependency change of `when`. `WriteSignal::set` notifies
/// unconditionally (even when the value is unchanged), so an effect
/// keyed on a signal `when` reads would otherwise tear down and
/// re-mount its branch for a no-op write — churning the DOM, disposing
/// the branch's internal reactive state, re-firing its `on_mount`, and
/// (through phantom hoisting) re-anchoring the *following siblings*,
/// which resigns a sibling native input's focus. Tracking the last
/// condition and skipping the rebuild avoids all of that. `when.call()`
/// is still evaluated every run, so the effect's dependency
/// subscription is preserved.
#[component]
pub fn show(
    when: WhenFn,
    children: Children,
    #[prop(default = ::std::default::Default::default())] fallback: Fallback,
) -> Element {
    let frag = create_phantom_element();

    type Mounted = Rc<RefCell<Option<(Owner, Vec<Element>)>>>;
    let mounted: Mounted = Rc::new(RefCell::new(None));
    // The condition the mounted branch reflects; `None` until first run.
    let last_cond: Rc<Cell<Option<bool>>> = Rc::new(Cell::new(None));

    // The outer body is a `FnMut`, so props are cloned in rather than
    // moved out of it. `Rc<dyn Fn>` clones are cheap.
    let when = when.clone();
    let children = children.clone();
    let fallback = fallback.clone();

    effect(move || {
        // Evaluate on every run to keep the dependency subscription,
        // but only rebuild when the condition actually changed.
        let cond = when.call();
        if last_cond.get() == Some(cond) {
            return;
        }
        last_cond.set(Some(cond));

        if let Some((owner, handles)) = mounted.borrow_mut().take() {
            for h in handles {
                remove_child(frag, h);
            }
            owner.dispose();
        }

        if cond {
            let owner = Owner::new(None);
            let handles = owner.with(|| {
                let view = children();
                view.attach_to(frag)
            });
            *mounted.borrow_mut() = Some((owner, handles));
        } else if let Some(fb) = &fallback.0 {
            let owner = Owner::new(None);
            let handle = owner.with(|| {
                let h = fb();
                append_child(frag, h);
                h
            });
            *mounted.borrow_mut() = Some((owner, vec![handle]));
        }
    });

    frag
}
